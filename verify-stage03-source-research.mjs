import fs from 'node:fs';
import vm from 'node:vm';
const assert=(condition,message)=>{if(!condition)throw new Error(message);};
globalThis.Event=globalThis.Event||class Event{constructor(type){this.type=type;}};
globalThis.dispatchEvent=globalThis.dispatchEvent||(()=>true);
for(const file of ['workbook.js','hash.js','workflow-schema.js'])vm.runInThisContext(fs.readFileSync(file,'utf8'),{filename:file});
const schema=globalThis.closedLoopWorkflowSchema;
assert(schema,'Workflow schema failed to load.');
const complete=schema.operationContract(3,'COMPLETE');
const challenge=schema.operationContract(3,'SEMANTIC_CHALLENGE');
const reconcile=schema.operationContract(3,'RECONCILE_RESEARCH');
assert(complete.agentWritableCollections.includes('research')&&complete.agentWritableCollections.includes('candidateRequirements'),'Stage 03 COMPLETE lost author research families.');
assert(challenge.agentWritableCollections.includes('semanticChallenges'),'Stage 03 SEMANTIC_CHALLENGE does not write the durable semanticChallenges family.');
assert(!challenge.agentWritableCollections.includes('research')&&!challenge.agentWritableCollections.includes('candidateRequirements'),'Stage 03 challenger can overwrite the author extraction.');
assert(challenge.readCollections.includes('sources'),'Stage 03 challenge cannot inspect the accepted source set.');
assert(!challenge.readCollections.includes('research')&&!challenge.readCollections.includes('candidateRequirements'),'Stage 03 omission challenger receives the first extraction before completing its independent pass.');
assert(reconcile.agentWritableCollections.includes('semanticReviews'),'Stage 03 RECONCILE_RESEARCH does not create the durable reconciliation review record.');
for(const family of ['research','candidateRequirements','semanticChallenges'])assert(reconcile.readCollections.includes(family),`Stage 03 reconciliation omits ${family}.`);
console.log(JSON.stringify({stage03SourceResearchOperationClosure:true}));
