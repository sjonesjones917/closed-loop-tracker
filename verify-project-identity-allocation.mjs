import assert from 'node:assert/strict';
import {projectStoreRuntime} from './test-project-store-runtime.mjs';
const r=projectStoreRuntime(),{store,rows}=r,cases=[],note=name=>cases.push({name,result:'PASS'});
assert.equal(typeof store.createProject,'function','PROJECT_CREATION_ORACLE: project creation needs one transactional application owner');
const a=await store.createProject({commandId:'CREATE-A'});
assert.match(a.job.JOB_ID,/^JOB-[0-9a-v]{32}$/,'PROJECT_ID_ORACLE: job identity must use closed-loop-id/1');
const receipt=a.projectData.allocationReceipts.find(row=>row.resultingId===a.job.JOB_ID);
assert.ok(receipt);assert.equal(receipt.familyPrefix,'JOB');
assert.equal(receipt.inputTuple.jobNamespace,'closed-loop-global/project-metadata');
assert.equal((await store.historyList(a.job.JOB_ID)).entries.length,1);
assert.deepEqual(await store.createProject({commandId:'CREATE-A'}),a);
note('Project creation atomically retains canonical identity, command receipt, and initial recovery checkpoint; exact retry returns the same project');
const b=await store.createProject({commandId:'CREATE-B'});assert.notEqual(a.job.JOB_ID,b.job.JOB_ID);
assert.equal(b.projectData.allocationReceipts.find(row=>row.resultingId===b.job.JOB_ID).allocationSequence,receipt.allocationSequence+1);
note('Independently authorized projects reserve distinct monotonic allocations in the registered global namespace');
const before=[...rows.get('projects').keys()],allocation=await store.metaGet('canonicalProjectAllocation');
r.runtime.__closedLoopStorageFault='before-transaction-commit';
await assert.rejects(store.createProject({commandId:'CREATE-FAIL'}),error=>error.code==='INJECTED_STORAGE_FAILURE');
delete r.runtime.__closedLoopStorageFault;
assert.deepEqual([...rows.get('projects').keys()],before);
assert.deepEqual(await store.metaGet('canonicalProjectAllocation'),allocation);
const recovered=await store.createProject({commandId:'CREATE-FAIL'});assert.ok(recovered.job.JOB_ID);
note('Interrupted creation leaves project, allocation sequence, receipts, and recovery history uncommitted; retry succeeds');
const backup=await store.exportPackage(a.job.JOB_ID),fresh=projectStoreRuntime();
const imported=await fresh.store.importPackage(backup);
assert.deepEqual(await fresh.store.createProject({commandId:'CREATE-A'}),imported);
assert.equal((await fresh.store.listProjectSummaries()).length,1);
note('Backup restoration retains completed creation identity and exact-retry protection without creating a second project');
console.log(JSON.stringify({synthetic:true,actualBrowser:false,environment:'Node production runtime with transactional test adapter',cases},null,2));
