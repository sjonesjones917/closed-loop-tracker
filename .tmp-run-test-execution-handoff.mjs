import fs from 'node:fs';
const target='.tmp-test-execution-handoff.mjs';
let source=fs.readFileSync(target,'utf8');
const before='\\`${path}/evidenceRefs\\`';
const after='\\`\\${path}/evidenceRefs\\`';
const count=source.split(before).length-1;
if(count!==3)throw new Error(`Expected three response-ingestion template anchors to escape; found ${count}.`);
source=source.replaceAll(before,after);
const oldSingle="fields:['TEST_ID','REQ_ID','TEST_TYPE','INPUTS','TOOLS','PROCEDURE','EXPECTED_RESULT','FAILURE_CONDITION','EVIDENCE_TO_PRESERVE','STATUS']";
const oldMulti="fields:[\n    'TEST_ID','REQ_ID','TEST_TYPE','INPUTS','TOOLS','PROCEDURE','EXPECTED_RESULT','FAILURE_CONDITION','EVIDENCE_TO_PRESERVE','STATUS'\n  ]";
const newSingle="fields:['TEST_ID','REQ_ID','TEST_TYPE','EXECUTION_MODE','REQUIRED_CAPABILITIES','EXECUTABLE_ARTIFACT_REQUIRED','INPUTS','TOOLS','PROCEDURE','EXPECTED_RESULT','FAILURE_CONDITION','EVIDENCE_TO_PRESERVE','STATUS']";
const newMulti="fields:[\n    'TEST_ID','REQ_ID','TEST_TYPE','EXECUTION_MODE','REQUIRED_CAPABILITIES','EXECUTABLE_ARTIFACT_REQUIRED','INPUTS','TOOLS','PROCEDURE','EXPECTED_RESULT','FAILURE_CONDITION','EVIDENCE_TO_PRESERVE','STATUS'\n  ]";
if(source.split(oldSingle).length-1!==1||source.split(newSingle).length-1!==1)throw new Error('Expected exactly one old and one new single-line tests schema literal in transformer.');
source=source.replace(oldSingle,oldMulti).replace(newSingle,newMulti);
fs.writeFileSync(target,source);
await import(`./${target}?fixed=${Date.now()}`);
