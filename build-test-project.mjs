import fs from 'node:fs';
import crypto from 'node:crypto';
const p=JSON.parse(fs.readFileSync('TEST_PROJECT.json','utf8'));
if(p.schema!=='human-project/30')throw new Error('TEST_PROJECT.json must use human-project/30');
if(p.currentStage!==30||Object.keys(p.stageStates||{}).length!==30)throw new Error('Test project must preserve exactly 30 stages');
if(!p.userJobInput?.objective?.includes('GEN-042'))throw new Error('Test project must be the real GEN-042 handoff job');
if(/application conformance|Evaluate the Closed-Loop Reliability application/i.test(JSON.stringify(p)))throw new Error('Self-referential app-conformance test project is prohibited');
const f=p.product?.files?.[0];
if(!f||crypto.createHash('sha256').update(f.content).digest('hex')!==f.sha256)throw new Error('Finished test-project product hash is invalid');
console.log('retained real test project validated; no fixture regeneration performed');
