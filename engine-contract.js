function buildPrompt(j,n,extra=""){
  if(n===1) throw new Error("Stage 1 is performed by the app from job intake; it is not an agent prompt.");
  const prior=relevantPrior(j,n);
  return `${promptHeader(j,n)}

WORK TO PERFORM NOW
${STAGE_INSTRUCTIONS[n]}

INPUT FROM COMPLETED EARLIER STAGES
${prior||"No earlier agent-produced stage output is required beyond the JOB RECORD."}

${extra?`STAGE-SPECIFIC FROZEN OR RUN INPUT
${extra}

`:""}REQUIRED RESPONSE
${exactOutputContract(n,j)}

OPERATING RULES THAT APPLY TO THIS WORK
${MANDATORY_RULES}

EXECUTION REQUIREMENT
Perform the work now. Do not return a checklist, plan, tutorial, or description of what another person should do in place of performing the work.
Use all tools and sources available to you that are required by this stage.
Do not invent missing facts.
Do not perform a later workflow stage in this response.
If a mandatory item cannot be established after using the available evidence and capabilities, identify it as UNKNOWN and BLOCK the affected work as required by the workflow.`;
}
function parseBool(text,key){
  const m=text.match(new RegExp("(?:^|\\n)\\s*"+key+"\\s*:\\s*(TRUE|FALSE|UNKNOWN)\\b","i")); return m?m[1].toUpperCase():null;
}
function parseNumber(text,key){
  const m=text.match(new RegExp("(?:^|\\n)\\s*"+key+"\\s*:\\s*([0-9]+(?:\\.[0-9]+)?%?)","i")); return m?m[1]:null;
}
function assignBlankIds(j,n,text){
  const fieldPrefix={2:["SOURCE_ID","SRC"],4:["REQ_ID","REQ"],6:["TEST_ID","TEST"],14:["DEFECT_ID","DEFECT"],15:["REG_ID","REG"],10:["FREEZE_ID","FREEZE"],20:["BASELINE_ID","BASELINE"],21:["PRODUCT_ID","PRODUCT"]};
  const p=fieldPrefix[n]; if(!p) return text;
  const [field,prefix]=p;
  const re=new RegExp("("+field+"\\s*:\\s*)(?=\\n|\\[leave blank|AUTO|$)","gi");
  return text.replace(re,()=>"$1"+nextId(j,prefix));
}

Object.assign(E,{exactOutputContract,buildPrompt,parseBool,parseNumber,assignBlankIds});
