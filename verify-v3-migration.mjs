import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

globalThis.Event=globalThis.Event||class Event{constructor(type){this.type=type;}};
globalThis.dispatchEvent=globalThis.dispatchEvent||(()=>true);
for(const file of ['workbook.js','hash.js','workflow-schema.js','test-runtime.js','workflow-engine.js'])vm.runInThisContext(fs.readFileSync(file,'utf8'),{filename:file});
const schema=globalThis.closedLoopWorkflowSchema,engine=globalThis.closedLoopWorkflowEngine;
const clone=v=>JSON.parse(JSON.stringify(v));
assert.equal(typeof schema.migrateProjectToCurrent,'function');
const legacy=JSON.parse(fs.readFileSync('TEST_PROJECT.json','utf8'));
assert.equal(legacy.schema,'human-project/30');
const fromLegacy=schema.migrateProjectToCurrent(clone(legacy));
assert.equal(fromLegacy.schema,'closed-loop-project/3');
assert.equal(fromLegacy.workflow,'mobile-closed-loop/30');
assert.equal(Number(fromLegacy.stageCount),30);
assert.equal(Object.keys(fromLegacy.stages||{}).length,30);
assert.equal(String(fromLegacy.job?.JOB_ID||fromLegacy.jobId),String(legacy.jobId));
assert.ok((fromLegacy.projectData?.nonOperationalImportedPayloads||[]).some(x=>x.sourceSchema==='human-project/30'&&x.operational===false),'Legacy source payload was not preserved as non-operational audit evidence.');
const v2=clone(fromLegacy);
v2.schema='closed-loop-project/2';
v2.extensions={unknownFutureData:{preserve:true}};
v2.projectData.rawResponses=v2.projectData.rawResponses||[];
v2.projectData.rawResponses.push({rawResponseId:'RAW-V2-HISTORICAL',responseSchema:'closed-loop-stage-response/2',completeRawResponse:'{"schema":"closed-loop-stage-response/2"}'});
v2.projectData.extractionManifests=v2.projectData.extractionManifests||[];
v2.projectData.extractionManifests.push({manifestId:'MANIFEST-V2-HISTORICAL',historical:true});
const fromV2=schema.migrateProjectToCurrent(v2);
assert.equal(fromV2.schema,'closed-loop-project/3');
assert.deepEqual(fromV2.extensions,{unknownFutureData:{preserve:true}},'Unknown extension data was lost.');
assert.ok(fromV2.projectData.rawResponses.some(x=>x.rawResponseId==='RAW-V2-HISTORICAL'),'Historical /2 raw response was lost.');
assert.ok(fromV2.projectData.extractionManifests.some(x=>x.manifestId==='MANIFEST-V2-HISTORICAL'),'Historical extraction manifest was lost.');
assert.ok(fromV2.projectData.nonOperationalImportedPayloads.some(x=>x.sourceSchema==='closed-loop-project/2'&&x.operational===false),'Original /2 payload was not archived as non-operational evidence.');
assert.equal(Object.keys(fromV2.stages||{}).length,30);
engine.ensureShape(fromV2);engine.recalculate(fromV2);
assert.equal(Object.keys(fromV2.stages||{}).length,30,'Migration created or removed a stage.');
for(const forbidden of ['31'])assert.equal(fromV2.stages?.[forbidden],undefined,'Migration created Stage 31.');
const currentAgain=schema.migrateProjectToCurrent(clone(fromV2));
assert.equal(currentAgain.schema,'closed-loop-project/3');
assert.equal(Object.keys(currentAgain.stages||{}).length,30);
console.log(JSON.stringify({legacyToV3:true,v2ToV3:true,unknownExtensionsPreserved:true,historicalRawResponsesPreserved:true,originalPayloadArchived:true,stageCount:30},null,2));
