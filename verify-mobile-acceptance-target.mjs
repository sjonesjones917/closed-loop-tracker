import assert from 'node:assert/strict';
import {createMobileAcceptanceTarget,MOBILE_ACCEPTANCE_ORIGIN,MOBILE_ACCEPTANCE_BASE_PATH} from './generate-mobile-acceptance-target.mjs';

const input={
  sourceCommit:'f'.repeat(40),deploymentManifestDigest:'a'.repeat(64),
  origin:MOBILE_ACCEPTANCE_ORIGIN,basePath:MOBILE_ACCEPTANCE_BASE_PATH,
  testProjectId:'JOB-MOBILE-001',procedureVersion:'actual-iphone-safari/1',
  viewport:{width:393,height:852,devicePixelRatio:3},
  deviceModel:'iPhone 15',iosVersion:'19.0',safariVersion:'19.0',
  safariUserAgent:'Mozilla/5.0 (iPhone; CPU iPhone OS 19_0 like Mac OS X) AppleWebKit/605.1.15 Version/19.0 Mobile/15E148 Safari/604.1',
  issuedAt:'2026-09-03T00:00:00.000Z',challengeLifetimeSeconds:3600
};
const target=createMobileAcceptanceTarget(input);
const second=createMobileAcceptanceTarget(input);
assert.match(target.challenge,/^[0-9a-f]{64}$/);
assert.notEqual(target.challenge,second.challenge,'Challenges must be generated by the CSPRNG and not repeat.');
assert.match(target.challengeIssuedAt,/^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d{3}Z$/);
assert.match(target.challengeExpiresAt,/^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d{3}Z$/);
assert.equal(target.challengeExpiresAt,'2026-09-03T01:00:00.000Z');
for(const key of ['sourceCommit','deploymentManifestDigest','origin','basePath','testProjectId','procedureVersion','viewport','deviceModel','iosVersion','safariVersion','safariUserAgent'])assert.throws(()=>createMobileAcceptanceTarget({...input,[key]:key==='viewport'?undefined:''}),new RegExp(key));
assert.throws(()=>createMobileAcceptanceTarget({...input,origin:'https://example.invalid'}),/canonical/);
assert.throws(()=>createMobileAcceptanceTarget({...input,basePath:'/'}),/canonical/);
assert.throws(()=>createMobileAcceptanceTarget({...input,challengeLifetimeSeconds:59}),/between/);
assert.throws(()=>createMobileAcceptanceTarget({...input,issuedAt:'2026-09-03T00:00:00Z'}),/canonical/);
assert.throws(()=>createMobileAcceptanceTarget({...input,issuedAt:'2026-02-30T00:00:00.000Z'}),/canonical/);
const mutated={...target,deploymentManifestDigest:'b'.repeat(64)};
assert.notEqual(mutated.deploymentManifestDigest,target.deploymentManifestDigest);
console.log(JSON.stringify({mobileAcceptanceTargetGenerator:'PASS',csprngChallengeShape:true,nonrepeatable:true,requiredInputsRejected:true,canonicalBindingEnforced:true,strictUtcAndExpiry:true,mutationSensitive:true},null,2));
